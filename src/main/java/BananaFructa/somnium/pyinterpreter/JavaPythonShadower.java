    public static boolean isNumber(String s) {
        if (s.isEmpty()) return false;
        if (s.charAt(0) == '.') return false;// this is valid but makes attribute code easier
        if (s.startsWith("0x")) {
            for (int i = 2;i < s.length();i++) {
                if (!(isLetter(s.charAt(i)) || isNumber(s.charAt(i)))) return false;
            }
        } else {
            for (char c : s.toCharArray()) if (!isNumber(c) && c != '.') return false;
        }
        return true;
    }

    public static boolean isWord(String s) {
        if (!isLetter(s.charAt(0))) return false;
        for (char c : s.toCharArray()) if (!(isLetter(c) || isNumber(c))) return false;
        return true;
    }

