    public static String iterateUntil(PointedString string, Function<Character, Boolean> condition) {
        String data = "";
        while (string.hasNext() && condition.apply(string.peek())) data += string.next();
        return data;
    }

    public static boolean isString(String token) {
        return isDoubleQute(token.charAt(0)) || isSingleQutoe(token.charAt(0));
    }

    // TODO: this does not take into account if # is inside a string
    public static String removeComments(String s) {
        String left = "";
        for (String line : s.split("\n")) {
            boolean content = false;
            for (int i = 0;i < line.length();i++) {
                if (!content && (line.charAt(i) == ' ' || line.charAt(i) == '\t')) continue;
                if (line.charAt(i) == '#') {
                    if (content) {
                        left += line.substring(0,i) + '\n';
                    }
                    break;
                } else {
                    content = true;
                    if (i == line.length() - 1) {
                        left += line + '\n';
                    }
                }
            }
        }
        return left;
    }

    public static List<List<String>> tokeniser(String code) {

        String[] lines = code.split("\n");
        List<List<String>> allTokens = new ArrayList<>();
        for (String line : lines) {
            PointedString s = new PointedString(line);
            List<String> tokens = new ArrayList<>();
            while (s.hasNext()) {
                char start = s.peek();
                boolean trailingWhiteSpace = false;
                while (start == ' ' || start == '\t' || start == '\r' || start == '\n') {
                    s.next(); // skip white spaces
                    if (!s.hasNext()) {
                        trailingWhiteSpace = true;
                        break;
                    }
                    start = s.peek();
                }
                if (trailingWhiteSpace) break;
                if (isLetter(start)) tokens.add(iterateUntil(s, (c) -> { // word
                    return isLetter(c) || isNumber(c);
                }));
                else if (isNumber(start)) {
                    if (start == '0' && s.hasNext(1) && s.peek(1) == 'x') {
                        String tks = "" + s.next() + s.next();
                        tokens.add(tks + iterateUntil(s, (c) -> {
                            return isNumber(c) || isLetter(c);
                        }));
                    } else {
                        tokens.add(iterateUntil(s, (c) -> {
                            return isNumber(c) || c == '.' || c == 'x';
                        }));
                    }
                }
                else if (isDoubleQute(start)) {
                    s.next();
                    // TODO: this string parsing doesn't take any special characters into account
                    String text = start + iterateUntil(s,(c) -> {
                        return !isDoubleQute(c);
                    });
                    text += s.next();
                    tokens.add(text);
                } else if (isSingleQutoe(start)) {
                    s.next();
                    // TODO: this string parsing doesn't take any special characters into account
                    String text = start + iterateUntil(s,(c) -> {
                        return !isSingleQutoe(c);
                    });
                    text += s.next();
                    tokens.add(text);
                }
                else {
                    String tf = Character.toString(s.next());
                    if (s.hasNext()) { // this is to support operators with 2 characters
                        String tff = tf + Character.toString(s.peek());
                        if (isOperator(tff) != -1) {
                            tokens.add(tff);
                            s.next();
                        } else tokens.add(tf);
                    } else tokens.add(tf);
                }

            }
            if (!tokens.isEmpty()) allTokens.add(tokens);
        }
        return allTokens;
    }

    public static boolean isExpressionTerm(ASTNode n) {
        return n instanceof ASTNumber || n instanceof ASTVariable || n instanceof ASTFunction || n instanceof ASTList || n instanceof ASTTuple || n instanceof ASTString || n instanceof ASTLambda || n instanceof ASTConditional;
    }

    public static boolean pushOperand(ASTNode head, ASTNode leaf) {
        if (!(head instanceof ASTOperator)) return false;
        if (!((ASTOperator) head).full()) {
            head.children.add(leaf);
            leaf.parent = head;
            return true;
        } else {
            if (head.children.get(((ASTOperator) head).unary ? 0 : 1) instanceof ASTOperator) return pushOperand(head.children.get(((ASTOperator) head).unary ? 0 : 1),leaf);
            else return false;
        }
    }

    private static void addChild(ASTNode parent, ASTNode child,Definitions definitions) {
        child.parent = parent;
        parent.children.add(child);
    }

    public static ASTNode pushOperator(ASTNode head, ASTNode leaf, Definitions definitions) {
        if (!(head instanceof ASTOperator)) { // If the head is an operand and the leaf is an operator
            leaf.parent = head.parent;
            addChild(leaf,head,definitions);
            //head.parent = leaf;
            //leaf.children.add(head);

            if (leaf.parent != null) {
                leaf.parent.children.remove(((ASTOperator) leaf.parent).unary ? 0 : 1);
                //leaf.parent.children.add(leaf);
                addChild(leaf.parent,leaf,definitions);
            }
            return leaf;
        } else if (((ASTOperator)leaf).precedence > ((ASTOperator)head).precedence) { // if two operators need to be joined where the leaf has higher precedence
            // This error is a bit harder to implement I guess it will just have to be sorted at runtime, by a bad operand type thing;
            //if (!((ASTOperator) head).full() && !((ASTOperator) leaf).unary) throw new RuntimeException("LID Python: Operator one after the other");
            if (((ASTOperator) head).full()) pushOperator(head.children.get(((ASTOperator) head).unary ? 0 : 1),leaf,definitions); // Check the right leaf of the head to push the leaf
            else {
                //head.children.add(leaf); // If the operator has children available then just push it
                //leaf.parent = head;
                addChild(head,leaf,definitions);
            }
            return head;
        } else {
            leaf.parent = head.parent; // if the precedence of the leaf is smaller it can be pushed
            addChild(leaf,head,definitions);
            //head.parent = leaf;
            //leaf.children.add(head);
            if (leaf.parent != null) {
                leaf.parent.children.remove(((ASTOperator) leaf.parent).unary ? 0 : 1);
                //leaf.parent.children.add(leaf);
                addChild(leaf.parent,leaf,definitions);
            }
            return leaf;
        }
    }

    static ASTNode pushToAST(ASTNode head, ASTNode other, Definitions definitions) {
        if (other instanceof ASTOperator) return pushOperator(head, other, definitions);
        // If the incoming operator has all of its children filled it must mean it was processed first, which happens in the case of it being place in brackets
        if (isExpressionTerm(other) || (other instanceof ASTOperator && ((ASTOperator)other).full())) {
            if (!pushOperand(head,other)) throw new RuntimeException("LID Python: Term one after the other");
            return head;
        }
        throw new RuntimeException("LID Python: Invalid symbol sequence.");
    }

    public static List<String> collectContainedTokens(PointedTokenSpace tokens, Function<String,Boolean> begin, Function<String,Boolean> end) {
        int nesting = 1;
        List<String> between = new ArrayList<>();
        do {
            while (tokens.hasNext() && nesting != 0) {
                if (begin.apply(tokens.peek())) nesting++;
                if (end.apply(tokens.peek())) nesting--;
                if (nesting != 0) between.add(tokens.peek());
                tokens.next();
            }
            if (nesting == 0) break;
            else tokens.nextLine();
        } while (tokens.hasLine());
        if (nesting != 0) throw new RuntimeException("LID Python: Bracket not closed");
        return between;
    }

    public static List<ASTNode> collectContainedList(PointedTokenSpace tokens, Function<String,Boolean> begin, Function<String,Boolean> end, Definitions definitions, HashMap<String, List<String>> linkedSymbolicFunctions) {
        List<String> between = collectContainedTokens(tokens,begin,end);

        List<String> parameterExpression = new ArrayList<>();
        List<ASTNode> parameterNodes = new ArrayList<>();

        int nestingParams = 0;
        int nestingList = 0;
        boolean inLambda = false;

        for (String t : between) {
            if (isComma(t) && nestingParams == 0 && nestingList == 0 && !inLambda) {
                parameterNodes.add(parseExpression(PointedTokenSpace.fromSingleLine(parameterExpression),definitions,linkedSymbolicFunctions));
                parameterExpression.clear();
            } else {
                if (isOpenBracket(t)) nestingParams++;
                if (isClosedBracket(t)) nestingParams--;
                if (isListStart(t)) nestingList++;
                if (isListEnd(t)) nestingList--;
                if (isLambda(t)) inLambda = true;
                if (inLambda && isColon(t)) inLambda = false;
                parameterExpression.add(t);
            }
        }
        if (!parameterExpression.isEmpty()) {
            parameterNodes.add(parseExpression(PointedTokenSpace.fromSingleLine(parameterExpression),definitions,linkedSymbolicFunctions));
            parameterExpression.clear();
        }

        return parameterNodes;
    }

    public static ASTNode parseExpression(PointedTokenSpace tokens, Definitions definitions, HashMap<String, List<String>> linkedSymbolicFunctions) {
        ASTNode head = null;
        ASTNode last = null;
        while(tokens.hasNext()) {
            String token = tokens.next();
            ASTNode other = null;
            if (isNumber(token)) {
                other = new ASTNumber(token);
            } else if (isOperator(token) != -1) {
                if (!(last instanceof ASTNumber || last instanceof ASTFunction || last instanceof ASTVariable) && token.equals("-")) {
                    ASTOperator op = new ASTOperator(token, isOperator(token));
                    op.unary = true;
                    other = op;
                } else {
                    ASTOperator op = new ASTOperator(token, isOperator(token));
                    op.unary = isUnary(token);
                    other = op;
                }
            } else if (isLambda(token)) {
                List<String> params = commaSplit(collectTokensUntil(tokens, JavaPythonShadower::isColon));
                tokens.next();
                String funcName = generateFunctionName(definitions.scopeCounter++);
                FunctionDefinition functionDefinition = new FunctionDefinition(funcName,params);
                definitions.put(funcName,functionDefinition);
                ASTLambda lambda = new ASTLambda(token);
                lambda.internalFunctionName = funcName;
                ASTNode innerLambda = parseExpression(tokens,definitions,linkedSymbolicFunctions);
                ASTReturn lambdaReturn = new ASTReturn("return");
                lambdaReturn.returnExp = innerLambda;
                definitions.get(funcName).expressions.add(lambdaReturn);
                other = lambda;
            } else if (isWord(token)) {
                if (!tokens.hasNext()) other = new ASTVariable(token);
                else if (isOpenBracket(tokens.peek())) {
                    tokens.next();
                    other = new ASTFunction(token);
                    List<ASTNode> params = collectContainedList(tokens,JavaPythonShadower::isOpenBracket,JavaPythonShadower::isClosedBracket,definitions,linkedSymbolicFunctions);
                    List<String> parameterNames = null;
                    if (definitions.containsKey(token)) {
                        if (((FunctionDefinition)definitions.get(token)).parameters.size() > params.size()) throw new RuntimeException("LID Python: Too many parameters for function call.");
                        if (((FunctionDefinition)definitions.get(token)).parameters.size() < params.size()) throw new RuntimeException("LID Python: Too little parameters for function call.");
                        parameterNames = ((FunctionDefinition)definitions.get(token)).parameters;
                    }
                    if (linkedSymbolicFunctions.containsKey(token)) {
                        if (linkedSymbolicFunctions.get(token).size() > params.size()) throw new RuntimeException("LID Python: Too many parameters for function call.");
                        if (linkedSymbolicFunctions.get(token).size() < params.size()) throw new RuntimeException("LID Python: Too little parameters for function call.");
                        parameterNames = linkedSymbolicFunctions.get(token);
                    }
                    HashMap<String,ASTNode> keywordArguments = new HashMap<>();
                    boolean endPositional = false;
                    for (ASTNode param : params) {
                        if (param instanceof ASTOperator && param.name.equals("=")) {
                            endPositional = true;
                            ASTOperator op = (ASTOperator) param;
                            if (!op.full()) throw new RuntimeException("LID Python: Equal hanging in keyword argument.");
                            if (parameterNames == null) throw new RuntimeException("LID Python: Function either doesn't exist or is not symbolically linked. Keyword parameters are not supported.");
                            if (keywordArguments.containsKey(op.children.get(0).name)) throw new RuntimeException("LID Python: Keyword argument already defined.");
                            keywordArguments.put(op.children.get(0).name,op.children.get(1));
                        } else {
                            if (endPositional) throw new RuntimeException("LID Python: Positional argument after keyword argument.");
                            other.children.add(param);
                            param.parent = other;
                        }
                    }
                    if (parameterNames != null) {
                        if (other.children.size() + keywordArguments.size() > parameterNames.size()) throw new RuntimeException("LID Python: Too many parameters for function call.");
                        if (other.children.size() + keywordArguments.size() < parameterNames.size()) throw new RuntimeException("LID Python: Too little parameters for function call.");
                        int diff = parameterNames.size() - other.children.size();
                        for (int i = 0;i < diff;i++) other.children.add(null);
                        for (String paramName : keywordArguments.keySet()) {
                            if (!parameterNames.contains(paramName)) throw new RuntimeException("LID Python: Parameter name doesn't exist.");
                            other.children.set(parameterNames.indexOf(paramName),keywordArguments.get(paramName));
                        }
                    }
                    for (ASTNode n : other.children) n.parent = other;
                } else other = new ASTVariable(token);
            } else if (isListStart(token)) {
                if (last instanceof ASTVariable || last instanceof ASTFunction || last instanceof ASTListAccessor) {
                    List<String> inBetween = collectContainedTokens(tokens,JavaPythonShadower::isListStart,JavaPythonShadower::isListEnd);
                    List<String> first = new ArrayList<>();
                    List<String> second = new ArrayList<>();
                    boolean range = false;
                    for (int i = 0;i < inBetween.size();i++) {
                        if (isColon(inBetween.get(i))) {
                            range = true;
                        } else if (!range) {
                            first.add(inBetween.get(i));
                        } else {
                            second.add(inBetween.get(i));
                        }
                    }
                    ASTListAccessor accessor = new ASTListAccessor("indexAccess");
                    if (!range) {
                        if (first.isEmpty()) throw new RuntimeException("LID Python: No index in list access.");
                        accessor.first = parseExpression(PointedTokenSpace.fromSingleLine(first),definitions,linkedSymbolicFunctions);
                    } else {
                        accessor.range = true;
                        if (first.isEmpty() && second.isEmpty()) throw new RuntimeException("LID Python: No index in list access.");
                        if (first.isEmpty()) accessor.first = null;
                        else accessor.first = parseExpression(PointedTokenSpace.fromSingleLine(first),definitions,linkedSymbolicFunctions);
                        if (second.isEmpty()) accessor.second = null;
                        else accessor.second = parseExpression(PointedTokenSpace.fromSingleLine(second),definitions,linkedSymbolicFunctions);
                    }
                    other = accessor;
                } else {
                    List<ASTNode> elements = collectContainedList(tokens,JavaPythonShadower::isListStart,JavaPythonShadower::isListEnd,definitions,linkedSymbolicFunctions);
                    ASTList list = new ASTList("list");
                    list.elements = elements;
                    other = list;
                }
            } else if (isOpenBracket(token)) {
                List<ASTNode> inner = collectContainedList(tokens,JavaPythonShadower::isOpenBracket,JavaPythonShadower::isClosedBracket,definitions,linkedSymbolicFunctions);
                if (inner.isEmpty()) throw new RuntimeException("LID Python: Brackets empty.");
                if (inner.size() == 1 && (tokens.peekPrev(2) == null || !isComma(tokens.peekPrev(2)))) {
                    other = inner.get(0);
                }
                else {
                    ASTTuple tuple = new ASTTuple("tuple");
                    tuple.elements.addAll(inner);
                    other = tuple;
                }
            } else if (isString(token)) {
                other = new ASTString(token.substring(1,token.length()-1));
            } else throw new RuntimeException("LID Python: Invalid Expression, token '"+token+"'.");

            if (tokens.hasNext()) { // Inline if statement
                String nextToken = tokens.peek();
                if (startOfIfStatement(nextToken)) {
                    tokens.next();
                    List<String> condition = collectTokensUntil(tokens,JavaPythonShadower::startOfElse);
                    ASTNode trueRet = other;
                    ASTNode cod = parseExpression(PointedTokenSpace.fromSingleLine(condition),definitions,linkedSymbolicFunctions);
                    tokens.next();
                    ASTNode falseRet = parseExpression(tokens,definitions,linkedSymbolicFunctions);
                    ASTConditional conditional = new ASTConditional("ternary");
                    conditional.condition = cod;
                    conditional.trueValue = trueRet;
                    conditional.falseValue = falseRet;
                    other = conditional;
                }
            }

            if (head == null) head = other;
            else head = pushToAST(head, other,definitions);
            last = other;
        }
        return head;
    }
